# 法律风险分析（默认按中国大陆现行法；其他法域使用前须替换本节）

先重申用户在前置门选择的场景（A–E 组合），扫描后证据若与之矛盾则再次确认，然后按适用场景输出两部分：

**一、我的法律地位与可用主张**（说明每条路径成立/受限及原因）
1. **个人信息权益路径**（个人信息保护法第 44/47/69 条、民法典第 1034–1038/995/1182/1183 条）：任何场景下，本人的账号信息、个人文档均可主张删除（第 47 条）与赔偿（第 69 条，过错推定）；
2. **消费者权益路径**（消保法第 8/29/50/55/56 条）：第 55 条三倍赔偿以"生活消费需要"为前提——A 场景最稳固；B、C 存在**裁判分歧**（经营性使用是否属生活消费，各地认定不一），须标注不确定性；D、E 采购主体为公司，原则上不适用；
3. **合同路径**（民法典第 577/584/148/152/157/496/497 条）：全场景可用——实际数据处理与协议披露不符可主张违约或欺诈撤销、返还费用；对方免责/限责格式条款依第 497 条主张无效；标注第 152 条一年除斥期间；
4. **商业秘密路径**（反不正当竞争法第 9 条；该法 2025 年修订，引用时提醒用户核对现行条文序号）：B 涉自身经营秘密；C/D/E 涉雇主商业秘密，但**权利主体可能是公司而非本人**，须先厘清"谁有权起诉"。

**二、场景特有风险**（仅分析适用项）
- **C**：本人对雇主的保密义务（劳动合同法第 23 条）与及时告知义务——迟延告知加重责任（第 90 条）；雇主才是适格原告，可推动雇主向平台主张；
- **D/E**：公司对下游客户的合同与数据保护义务，可能触发对客户的违约责任及监管报告义务（个保法第 57 条、数据安全法第 29 条），形成"平台—公司—客户"链式责任；
- **E**：若被上传内容含终端用户个人信息，公司自身同时构成泄露事件责任方，应同步留存向平台追偿的证据；
- **混合场景**：按工作区归属标注拆分主张——个人信息部分由本人主张，公司数据/商业秘密部分由公司主张。

要求：法条引用准确到条号；裁判分歧明确标注；执行者若无法条检索工具，声明"基于模型自带法律知识整理，不构成正式法律意见"。最后按场景给出维权路径排序（个人发函/投诉/诉讼、公司违约与侵权之诉及追偿、12377 与 12315 行政举报——任何场景均可并行）。

