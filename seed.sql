# 硬性约束（全程有效，文书起草阶段同样适用）

- **只读**：不删、不改、不移动任何既有文件，不发起网络请求，不卸载软件；新建文件仅限本任务工件（清单/哈希/报告/文书）；
- **凭据一律脱敏**（前 4 字符 + 长度），报告、过程输出与文书中不得出现完整密钥；不打开凭据文件内容，只列文件名/大小/mtime；
- **利益冲突声明**：若执行者本身就是被排查工具之一，报告开头必须声明，并建议用户对自查部分独立复核；若被起诉/举报对象即执行者所属厂商，文书起草前须再次提示该利益冲突；
- **禁止编造**：查不到就写"未发现"并列出已查位置；禁止编造路径和数据；每条定性标注证据强度（实锤/推断/未发现）；文书中禁止编造用户未提供的事实、数字与当事人信息；
- **系统兼容**：先检测操作系统与可用 shell（bash / PowerShell / cmd），只使用该环境实际存在的只读命令，路径按各 OS 惯例枚举（Windows：用户主目录 + AppData\Roaming + AppData\Local + 注册表卸载项；macOS：`~/Library/Application Support`、`~/Library/Preferences`；Linux：`~/.config`、`~/.local/share`）。给出等价命令而非唯一命令；
- **编码兼容**：中文 Windows 上 PowerShell/cmd 重定向输出可能为 UTF-16/GBK，解析前先去 NUL 字节或改用 python 读取；环境中有 python 时优先用 python 做 JSON 解析与脱敏处理。

# 方法论：三级扫描（按前置门所选模式裁剪）

**L0 存在性与体积（每工具秒级）**：枚举候选目录是否存在、总体积（du 等价命令）、最近写入时间；目录不存在/为空/纯程序二进制与缓存 → 直接记"未发现"，不再深入。优先实测枚举本机实际数据目录（解析符号链接），通用文档路径仅作兜底，不硬套。

**L1 痕迹筛查（每工具限时约 10 分钟）**：在数据目录内按固定模式检索——
- 文件名模式：`manifests/*.json`、`pending/*.tar.gz`、`pending/*.enc`、`*.envelope.json`、`state.json`、文件名或字段含 `upload/accepted/manifest/snapshot/sync` 的状态文件；
- 日志尾部（大日志先取末尾 20MB）grep 上传关键词（upload/snapshot/manifest/collect）与外部域名 top-N（对象存储域名 oss/cos/s3/obs/tos/myqcloud/aliyuncs 重点标注，并区分上传/下载方向）；
- 任一采集模式命中 → 进入 L2；未命中 → 记"未发现"并列入覆盖面清单。

**L2 深度取证（仅模式二点名工具 / 模式三全部 / L1 命中者；每工具限时约 20 分钟）**：完整解析状态机（工作区路径、送达/接受字段、重试计数、滞留队列）、manifest 内敏感文件名扫描、`.git` 历史包含度、密钥归属判定（本地持有 vs 服务端公钥包裹）、开关存在性排查。

**参考模式**（同机已证实的采集形态，用于类比检索，不得硬套）：某目录下同时出现 manifests/*.json（逐文件清单 path+sizeBytes）、pending/*.tar.gz.enc（加密打包产物）、*.envelope.json（非对称包裹数据密钥的信封，keyId 指向服务端持有私钥）、state.json（含 workspacePath / lastAcceptedManifestHash / failureCount / activeUpload / pendingUpload 类字段）。

**哈希固定规则**：仅对证据文件（清单/状态机/信封/加密包/关键日志）计算 SHA-256；单文件超过 100MB 只记路径+大小并注明"超限未哈希"；程序二进制、模型权重、媒体与浏览器缓存一律不哈希。哈希清单边扫边追加写入工件目录。

**效率纪律**：
- 主控先做**一次**全机枚举（用户主目录、AppData 两级/系统等价位置、已安装程序清单），把确认存在的工具与路径清单连同参考模式**直接下发各子代理**，子代理不得重复全局枚举；无子代理能力则按清单顺序执行；
- 严格按 L1/L2 时限执行，超时未收敛 → 记录"部分覆盖"并转向下一工具，禁止无预算拖延；整体超时则输出"部分覆盖报告"并如实标注；
- **中间产物落盘**：枚举清单、每工具结论、哈希清单逐条写入工件目录，防止长会话上下文压缩丢失；最终报告引用文件而非全量粘贴。

# 对每份采集痕迹的定性三问

① **收集了什么**：范围是否超出"我在对话中主动提交的内容"，是否含 .git 历史、凭据文件、个人文档；
② **是否已送达**：区分"服务端已接收"与"本地滞留/重试中"——找可判定接收状态的字段（accepted/ack/200 状态码/服务端下发凭据）或日志；网络层确认不可得时，如实标注置信度；
③ **我能否控制**：相关开关关闭后是否真的停止（找落盘配置证据，界面开关不见得可靠），数据我本地能否解密（密钥在谁手里——本地 master key vs 服务端公钥包裹）。

**定级**：敏感内容 × 送达状态 → 高 / 中 / 低。

